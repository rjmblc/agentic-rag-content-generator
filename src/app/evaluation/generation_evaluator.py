from src.app.llm import create_llm


# ============================================================
# FAITHFULNESS EVALUATION
# ============================================================

FAITHFULNESS_PROMPT = """
You are evaluating the faithfulness of an answer generated by an AI system.

Your task is to determine whether the ANSWER is supported by the CONTEXT.

IMPORTANT RULES:

1. Only use information explicitly supported by the CONTEXT.
2. Do not use your own outside knowledge.
3. A claim is faithful if the context supports it directly or clearly implies it.
4. Penalize claims that are invented, unsupported, or contradict the context.
5. Focus on factual claims, not wording or writing quality.
6. Do not penalize reasonable summarization or paraphrasing.
7. If most claims are supported but a few are unsupported, give a partial score.

SCORING:

1.0 = All or almost all factual claims are supported.
0.8 = Most claims are supported, with minor unsupported additions.
0.6 = A significant portion is supported, but several claims are unsupported.
0.4 = About half of the important claims are supported.
0.2 = Very little of the answer is supported.
0.0 = The answer is largely unsupported or contradicts the context.

Return EXACTLY:

SCORE: <number between 0.0 and 1.0>
REASON: <one short paragraph explaining the score>

================ CONTEXT ================

{context}

================ ANSWER ================

{answer}

==========================================
"""


def evaluate_faithfulness(context: str, answer: str) -> dict:

    llm = create_llm()

    prompt = FAITHFULNESS_PROMPT.format(
        context=context,
        answer=answer
    )

    response = llm.invoke(prompt)

    evaluation = response.content

    score = None
    reason = ""

    for line in evaluation.splitlines():

        line = line.strip()

        if line.startswith("SCORE:"):
            try:
                score = float(
                    line.replace("SCORE:", "").strip()
                )
            except ValueError:
                score = None

        elif line.startswith("REASON:"):
            reason = line.replace(
                "REASON:", ""
            ).strip()

    return {
        "faithfulness_score": score,
        "reason": reason,
        "raw_evaluation": evaluation
    }


